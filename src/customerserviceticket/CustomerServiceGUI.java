private void refreshTable() {
    

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblTickets.getModel();

    model.setRowCount(0);

    for (int i = 0; i < ticketManager.getSize(); i++) {

        Ticket ticket = ticketManager.getTicketAt(i);

        model.addRow(new Object[]{
            ticket.getTicketId(),
            ticket.getCustomerName(),
            ticket.getCategory(),
            ticket.getDescription(),
            ticket.getStatus()
        });
    }
}
private void clearFields() {

    txtTicketID.setText("");
    txtCustomerName.setText("");
    txtDescription.setText("");

    cmbCategory.setSelectedIndex(0);
    cmbStatus.setSelectedIndex(0);

    txtTicketID.requestFocus();
}
    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed

    String id = txtTicketID.getText().trim();
    String name = txtCustomerName.getText().trim();
    String category = cmbCategory.getSelectedItem().toString();
    String description = txtDescription.getText().trim();
    String status = cmbStatus.getSelectedItem().toString();

    try {

        if (id.isEmpty() || name.isEmpty() || description.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Please complete all required fields.");
            return;
        }

        Ticket newTicket;

        if (category.equals("General")) {
            newTicket = new GeneralTicket(
                    id, name, description, status, "General Concern"
            );
        } else {
            newTicket = new TechnicalTicket(
                    id, name, description, status,
                    "Not specified", description
            );
        }

        if (ticketManager.addTicket(newTicket)) {

            refreshTable();

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ticket added successfully!");

            clearFields();

        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ticket ID already exists!");
        }

    } catch (IllegalArgumentException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage());
    
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
       String id = txtTicketID.getText().trim();

    if (id.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please enter a Ticket ID to search.");
        return;
    }

    Ticket ticket = ticketManager.searchTicket(id);

    if (ticket != null) {

        txtCustomerName.setText(ticket.getCustomerName());
        cmbCategory.setSelectedItem(ticket.getCategory());
        txtDescription.setText(ticket.getDescription());
        cmbStatus.setSelectedItem(ticket.getStatus());

        javax.swing.JOptionPane.showMessageDialog(this,
                "Ticket found!");

    } else {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Ticket not found.");
    }

    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
    String id = txtTicketID.getText().trim();
    String newStatus = cmbStatus.getSelectedItem().toString();

    if (id.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please enter a Ticket ID first.");
        return;
    }

    try {

        if (ticketManager.updateTicketStatus(id, newStatus)) {

            refreshTable();

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ticket status updated successfully!");

            clearFields();

        } else {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ticket not found. Please check the Ticket ID.");
        }

    } catch (IllegalArgumentException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage());
    }
        
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
    String id = txtTicketID.getText().trim();

    if (id.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please enter a Ticket ID to delete.");
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete ticket " + id + "?",
            "Confirm Delete",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirm == javax.swing.JOptionPane.YES_OPTION) {

        if (ticketManager.deleteTicket(id)) {

            refreshTable();
            clearFields();

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ticket deleted successfully!");

        } else {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ticket not found.");
        }
    }
       
    }//GEN-LAST:event_btnDeleteActionPerformed

